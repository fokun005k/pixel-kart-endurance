const GLYPHS = {};
for (const [ch, rows] of Object.entries(RAW)) {
  const px = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x++) if (row[x] === '1') px.push(x, y);
  });
  GLYPHS[ch] = px;
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function measureText(text, scale = 1, spacing = 1) {
  const n = String(text).length;
  if (!n) return 0;
  return (n * (GLYPH_W + spacing) - spacing) * scale;
}

const cache = new Map();

function renderText(text, scale, color, shadow) {
  const key = `${text}|${scale}|${color}|${shadow || ''}`;
  let c = cache.get(key);
  if (c) return c;
  const sh = shadow ? scale : 0;
  c = document.createElement('canvas');
  c.width = Math.max(1, measureText(text, scale) + sh);
  c.height = GLYPH_H * scale + sh;
  const g = c.getContext('2d');
  const draw = (ox, oy, col) => {
    g.fillStyle = col;
    let cx = ox;
    for (const raw of String(text).toUpperCase()) {
      const px = GLYPHS[raw] || GLYPHS['?'];
      for (let i = 0; i < px.length; i += 2) g.fillRect(cx + px[i] * scale, oy + px[i + 1] * scale, scale, scale);
      cx += (GLYPH_W + 1) * scale;
    }
  };
  if (shadow) draw(sh, sh, shadow);
  draw(0, 0, color);
  if (cache.size > 600) cache.clear();
  cache.set(key, c);
  return c;
}

/**
 * Draw pixel text. align: 'left' | 'center' | 'right'
 */
export function drawText(g, text, x, y, scale = 2, color = '#fff', align = 'left', shadow = '#000') {
  const img = renderText(String(text), scale, color, shadow);
  let dx = x;
  if (align === 'center') dx = x - Math.floor(img.width / 2);
  else if (align === 'right') dx = x - img.width;
  g.drawImage(img, Math.round(dx), Math.round(y));
  return img.width;
}
